import React, { useEffect, useState } from "react";
import Header from "../components/Header";
import { getPredictionHistory } from "../api/predictions";

function History() {
    const [history, setHistory] = useState([]);
    const [loading, setLoading] = useState(true);

    useEffect(() => {
        async function loadHistory() {
            try {
                const data = await getPredictionHistory();
                setHistory(data);
            } catch (error) {
                console.error(error);
            } finally {
                setLoading(false);
            }
        }

        loadHistory();
    }, []);

    return (
        <>
            <Header />

            <div
                style={{
                    maxWidth: "1500px",
                    margin: "0 auto",
                    padding: "7rem 2rem 2rem",
                }}
            >
                {loading && <p>Loading prediction history...</p>}

                {!loading && history.length === 0 && (
                    <p>No prediction history available.</p>
                )}

                {!loading && history.length > 0 && (
                    <div
                        className="stat-card"
                        style={{
                            background: "#20232d",
                            border: "1px solid rgba(255,255,255,.08)",
                            borderRadius: "16px",
                            padding: "2rem",
                        }}
                    >
                        <div
                            style={{
                                display: "flex",
                                justifyContent: "space-between",
                                alignItems: "center",
                                marginBottom: "2rem",
                            }}
                        >
                            <div>
                                <h2 style={{ margin: 0 }}>
                                    Prediction History
                                </h2>

                                <p
                                    style={{
                                        marginTop: ".5rem",
                                        color: "#9ca3af",
                                        fontSize: "14px",
                                    }}
                                >
                                    Previous predictions generated by the
                                    system.
                                </p>
                            </div>

                            <span className="status-tag nominal">
                                {history.length} Records
                            </span>
                        </div>

                        <div style={{ overflowX: "auto" }}>
                            <table
                                style={{
                                    width: "100%",
                                    borderCollapse: "collapse",
                                }}
                            >
                                <thead>
                                    <tr>
                                        {[
                                            "Result",
                                            "Probability",
                                            "Age",
                                            "Sex",
                                            "Chest Pain",
                                            "Blood Pressure",
                                            "Cholesterol",
                                            "Max HR",
                                            "ST Slope",
                                            "Created",
                                        ].map((title) => (
                                            <th
                                                key={title}
                                                align="left"
                                                style={{
                                                    padding: "14px 12px",
                                                    borderBottom:
                                                        "2px solid rgba(255,255,255,.08)",
                                                    color: "#cbd5e1",
                                                    fontWeight: 600,
                                                    whiteSpace: "nowrap",
                                                }}
                                            >
                                                {title}
                                            </th>
                                        ))}
                                    </tr>
                                </thead>

                                <tbody>
                                    {history.map((prediction) => (
                                        <tr
                                            key={prediction.id}
                                            style={{
                                                borderBottom:
                                                    "1px solid rgba(255,255,255,.08)",
                                                height: "58px",
                                            }}
                                        >
                                            <td style={{ padding: "16px 12px" }}>
                                                <span
                                                    className={`status-tag ${
                                                        prediction.prediction === 1
                                                            ? "critical"
                                                            : "nominal"
                                                    }`}
                                                >
                                                    {prediction.prediction === 1
                                                        ? "Heart Disease"
                                                        : "No Heart Disease"}
                                                </span>
                                            </td>

                                            <td style={{ padding: "16px 12px" }}>
                                                {(prediction.probability * 100).toFixed(1)}%
                                            </td>

                                            <td style={{ padding: "16px 12px" }}>
                                                {prediction.input_snapshot?.Age}
                                            </td>

                                            <td style={{ padding: "16px 12px" }}>
                                                {prediction.input_snapshot?.Sex}
                                            </td>

                                            <td style={{ padding: "16px 12px" }}>
                                                {prediction.input_snapshot?.ChestPainType}
                                            </td>

                                            <td style={{ padding: "16px 12px" }}>
                                                {prediction.input_snapshot?.RestingBP}
                                            </td>

                                            <td style={{ padding: "16px 12px" }}>
                                                {prediction.input_snapshot?.Cholesterol}
                                            </td>

                                            <td style={{ padding: "16px 12px" }}>
                                                {prediction.input_snapshot?.MaxHR}
                                            </td>

                                            <td style={{ padding: "16px 12px" }}>
                                                {prediction.input_snapshot?.ST_Slope}
                                            </td>

                                            <td
                                                style={{
                                                    padding: "16px 12px",
                                                    whiteSpace: "nowrap",
                                                }}
                                            >
                                                {new Date(
                                                    prediction.created_at
                                                ).toLocaleString()}
                                            </td>
                                        </tr>
                                    ))}
                                </tbody>
                            </table>
                        </div>
                    </div>
                )}
            </div>
        </>
    );
}

export default History;
